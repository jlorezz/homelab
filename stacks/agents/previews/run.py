#!/usr/bin/env python3
"""Start this checkout's bounded NAS preview; owns only its own child processes."""
import argparse
import fcntl
import json
import os
from pathlib import Path
import signal
import subprocess
import sys
import time

HERE = Path(__file__).resolve().parent
STATE = Path.home()/'.nas-previews'
CONFIG = HERE/'configs'
MARKER = '# Generated by nas-preview; isolated development credentials only.\n'


def claim(root, create=True):
    STATE.mkdir(mode=0o700,exist_ok=True)
    with (STATE/'claims.lock').open('a') as lock:
        fcntl.flock(lock,fcntl.LOCK_EX)
        path=STATE/'claims.json'
        claims=json.loads(path.read_text()) if path.exists() else {}
        for slot,owner in claims.items():
            if owner==str(root): return json.loads((CONFIG/f'{slot}.json').read_text())
        if not create: return None
        for slot in (1,2):
            if str(slot) not in claims and (CONFIG/f'{slot}.json').exists():
                claims[str(slot)]=str(root)
                temp=path.with_suffix('.new');temp.write_text(json.dumps(claims));temp.chmod(0o600);temp.replace(path)
                return json.loads((CONFIG/f'{slot}.json').read_text())
        raise RuntimeError('Both NAS preview backends are assigned. Retain their data; ask the operator to retire an unused slot before assigning another checkout.')


def environment(config,root):
    env=dict(config['env'])
    origin=config['origin'];slot=config['slot']
    env.update({'DIRECT_DATABASE_URL':env['DATABASE_URL'],'NODE_ENV':'development',
                'DEALPIPE_DASHBOARD_PORT':str(4200+slot),'DEALPIPE_API_PORT':str(4300+slot),
                'NEXT_DEV_ALLOWED_ORIGIN':origin.split('://',1)[1].split(':')[0],
                'DEALPIPE_API_URL':f'http://127.0.0.1:{4300+slot}/graphql','NEXT_PUBLIC_DEALPIPE_API_URL':origin+'/graphql',
                'API_ALLOWED_ORIGINS':origin,'WORKFLOW_TARGET_WORLD':'local',
                'WORKFLOW_LOCAL_BASE_URL':origin,'WORKFLOW_LOCAL_DATA_DIR':str(root/'supabase/.temp/nas-workflow'),
                'NEXT_PUBLIC_APP_URL':origin,'NEXT_PUBLIC_DASHBOARD_URL':origin,'DASHBOARD_URL':origin,
                'NEXT_PUBLIC_SITE_URL':origin,'NEXT_PUBLIC_WEBSITE_URL':origin,'NEXT_TELEMETRY_DISABLED':'1',
                'UPSTASH_REDIS_REST_URL':env['KV_REST_API_URL'],'UPSTASH_REDIS_REST_TOKEN':env['KV_REST_API_TOKEN'],
                'NAS_PREVIEW_PROXY':json.dumps(config['proxy'])})
    # External provider credentials are deliberately absent. The root .env is
    # generated from this allowlist; never copy a desktop/hosted environment.
    destination=root/'.env'
    if destination.is_symlink() or (destination.exists() and not destination.read_text().startswith(MARKER)):
        raise RuntimeError('Existing .env is not owned by nas-preview. Use a clean dedicated worktree.')
    for app in ('dashboard','api'):
        if any((root/'apps'/app).glob('.env*')):
            # The tracked .env.example is documentation, not runtime configuration.
            if any(p.name!='.env.example' for p in (root/'apps'/app).glob('.env*')):
                raise RuntimeError(f'Remove or review existing apps/{app}/.env runtime overrides first.')
    content=MARKER+'\n'.join(k+'='+json.dumps(v) for k,v in env.items() if k!='NAS_PREVIEW_PROXY')+'\n'
    fd=os.open(destination,os.O_WRONLY|os.O_CREAT|os.O_TRUNC|os.O_NOFOLLOW,0o600)
    os.fchmod(fd, 0o600)
    with os.fdopen(fd,'w') as stream:stream.write(content)
    # Retain tools and certificate setup, not unrelated shell credentials.
    clean={k:os.environ[k] for k in ['HOME','PATH','SSL_CERT_FILE','GIT_SSL_CAINFO','LD_LIBRARY_PATH','FONTCONFIG_FILE','TMPDIR'] if k in os.environ}
    return {**clean,**env}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action',choices=['setup','run','status'])
    parser.add_argument('--timeout',type=int,default=1800,help='Preview/installation lifetime in seconds; default operator budget 30 minutes')
    parser.add_argument('--guarded',action='store_true',help=argparse.SUPPRESS)
    args=parser.parse_args()
    if args.timeout<=0:parser.error('--timeout must be positive')
    root=Path.cwd().resolve()
    if not (root/'scripts/supabase-worktree.py').is_file():raise RuntimeError('Run inside a Dealpipe checkout.')
    if args.action!='status' and not args.guarded:
        print('Waiting for the NAS workload slot (up to 30 minutes); active CI or previews finish first.', flush=True)
        os.execvp('agent-workload',['agent-workload','run','--queue-timeout','1800','--timeout',str(args.timeout),'--','python3',str(HERE/'run.py'),args.action,'--guarded','--timeout',str(args.timeout)])
    config=claim(root, create=args.action!='status')
    if config is None:
        print('This checkout has no NAS preview slot. Run nas-preview setup.');return
    print(f"NAS preview slot {config['slot']}: {config['origin']} | Mail: {config['origin']}/mail/",flush=True)
    if args.action=='status':return
    env=environment(config,root)
    subprocess.run(['bun','install','--frozen-lockfile'],cwd=root,env=env,check=True) if args.action=='setup' or (not (root/'node_modules/next').exists() and not (root/'apps/dashboard/node_modules/next').exists()) else None
    cookie_check = 'import { localAuthCookieOptions } from "./packages/supabase/src/client/cookie-options.ts"; if (localAuthCookieOptions(process.env.NEXT_PUBLIC_SUPABASE_URL)?.name !== process.env.NEXT_PUBLIC_SUPABASE_COOKIE_NAME) { console.error("This checkout needs the NAS preview cookie adapter before use. Select the NAS preview feature branch or apply its reviewed adapter commit."); process.exit(1); }'
    subprocess.run(['bun', '--eval', cookie_check], cwd=root, env=env, check=True)
    if args.action=='setup':
        receipt=STATE/f"{config['slot']}-initialized.json"
        if receipt.exists():
            print('Backend already initialized; data preserved. Apply future migrations explicitly.');return
        subprocess.run(['bun','packages/db/scripts/migrate.ts'],cwd=root,env=env,check=True)
        sql='import postgres from "postgres"; const db=postgres(process.env.DATABASE_URL); try { await db.unsafe(await Bun.stdin.text()); } finally { await db.end(); }'
        for file in ['supabase/seed.sql','supabase/seeds/crm-demo.sql']:
            subprocess.run(['bun','--eval',sql],input=(root/file).read_text(),cwd=root,env=env,text=True,check=True)
        receipt.write_text(json.dumps({'worktree':str(root),'commit':subprocess.check_output(['git','rev-parse','HEAD'],cwd=root,text=True).strip(),'initialized_at':time.time()}));receipt.chmod(0o600)
        print('Canonical migrations and development seeds applied only to this slot.');return
    if not (STATE/f"{config['slot']}-initialized.json").exists():raise RuntimeError('Run nas-preview setup first.')
    children=[]
    def stop(signum=None,frame=None):
        for child in children:
            try:child.terminate()
            except ProcessLookupError:pass
        deadline=time.monotonic()+1
        for child in children:
            try:child.wait(timeout=max(0.01,deadline-time.monotonic()))
            except subprocess.TimeoutExpired:
                try:child.kill()
                except ProcessLookupError:pass
                child.wait()
        if signum is not None:raise SystemExit(128+signum)
    for sig in (signal.SIGINT,signal.SIGTERM):signal.signal(sig,stop)
    try:
        subprocess.run(['bun','scripts/build.ts','--dev'],cwd=root/'apps/api',env=env,check=True)
        for command,cwd in [(['node','dist/dev.mjs'],root/'apps/api'),(['bun','run','dev','--hostname','localhost'],root/'apps/dashboard'),(['node',str(HERE/'proxy.mjs')],root)]:
            children.append(subprocess.Popen(command,cwd=cwd,env=env))
        deadline=time.monotonic()+args.timeout
        while all(child.poll() is None for child in children) and time.monotonic()<deadline:time.sleep(0.5)
        failed=next((child.returncode for child in children if child.returncode),0)
        if failed:raise RuntimeError(f'A preview service exited with status {failed}.')
    finally:stop()

if __name__=='__main__':
    try:main()
    except (OSError,ValueError,RuntimeError,subprocess.CalledProcessError) as exc:
        print(f'Preview failed: {exc}',file=sys.stderr);sys.exit(1)
